"""Source snapshots around a Bash call (KINIG-110): the second line of defence for CLAUDE.md rule 8.

`guard.py bash` records the dirty files of the Kinige checkout the command works in (the last `cd` or the hook's
`cwd`); `guard.py post` compares. A source file that the command created or rewrote, when the command ran no tool that
legitimately writes sources (a writing git subcommand, cargo, npm, a repo script...), was edited by a script: the agent
is told to undo that change and redo it with Edit or Write. This catches what the command-line patterns of `guard.py`
cannot see, such as `python3 /tmp/fix.py`, `eval` or a heredoc piped into `sh`. Deleting a file is not an edit and is
not reported.
"""

import hashlib
import json
import os
import re
import subprocess
import tempfile
import time

# A file under one of these is a source file for rule 8 (repo-relative paths).
SOURCE_DIRS = (
    "crates/", "src-tauri/", "web/", "server/", "spikes/", "scripts/", "docs/", "design/", "deploy/", "fixtures/",
    ".github/", ".claude/agents/", ".claude/hooks/", ".claude/skills/",
)
SOURCE_ROOT_SUFFIXES = (".toml", ".md", ".json", ".yml", ".yaml")

# Written by generators (cargo test, npm run tokens, screens runs) or by the harness itself, not by hand.
GENERATED = (
    "web/src/api/generated/", "web/src/ui/forest/fixtures/", "web/src/ui/tokens.css", "web/src/ui/themes.css",
    "docs/screens/", "src-tauri/gen/", "src-tauri/permissions/autogenerated/", "src-tauri/binaries/",
    "Cargo.lock", "web/package-lock.json", "claude-progress.md", ".claude/agent-memory/", ".claude/agent-memory-local/",
)

# A command that runs one of these may write sources on purpose; its changes are not attributed to a script edit.
WRITING_TOOLS = {
    "cargo", "rustup", "rustfmt", "npm", "npx", "pnpm", "mv", "cp", "patch", "unzip", "tar", "curl", "wget", "docker",
    "make", "codex",
}
GIT_WRITING = {
    "checkout", "switch", "restore", "apply", "am", "merge", "rebase", "reset", "stash", "pull", "cherry-pick", "revert",
    "mv", "rm", "clone", "worktree", "submodule", "bisect",
}
REPO_SCRIPT_PREFIXES = ("scripts/", "./scripts/", "deploy/", "./deploy/", "web/node_modules/.bin/", "node_modules/.bin/")
INTERPRETERS = {"bash", "sh", "zsh", "python", "python3", "node", "deno", "bun", "pwsh", "ruby", "perl"}

MARKER = os.path.join("crates", "kinige-domain", "Cargo.toml")
STALE_SECONDS = 24 * 3600


def kinige_root(path):
    """The top of the Kinige checkout or worktree that contains `path` (a directory), or None."""
    if not path or "$" in path or not os.path.isdir(path):
        return None
    try:
        out = subprocess.run(
            ["git", "-C", path, "rev-parse", "--show-toplevel"], capture_output=True, text=True, timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    root = out.stdout.strip()
    if out.returncode != 0 or not root or not os.path.isfile(os.path.join(root, MARKER)):
        return None
    return root


def dirty_files(root):
    """{repo-relative path: content hash or "-"} for every changed, deleted or untracked (not ignored) file."""
    out = subprocess.run(
        ["git", "--no-optional-locks", "-C", root, "status", "--porcelain=v1", "-z", "--untracked-files=all",
         "--no-renames"],
        capture_output=True, timeout=30,
    )
    if out.returncode != 0:
        return None
    result = {}
    for entry in out.stdout.decode("utf-8", "surrogateescape").split("\0"):
        if len(entry) < 4:
            continue
        path = entry[3:]
        result[path] = file_hash(os.path.join(root, path))
    return result


def file_hash(path):
    try:
        with open(path, "rb") as f:
            return hashlib.sha1(f.read()).hexdigest()
    except OSError:
        return "-"


def is_source(path):
    if any(path == g or path.startswith(g) for g in GENERATED):
        return False
    if path.startswith(SOURCE_DIRS):
        return "/node_modules/" not in path and "/target/" not in path
    return "/" not in path and path.endswith(SOURCE_ROOT_SUFFIXES)


def changed_sources(before, after):
    """Source files the command created or changed; a file that is gone afterwards was deleted, not edited."""
    paths = set(before) | set(after)
    return sorted(p for p in paths if before.get(p) != after.get(p) and after.get(p, "-") != "-" and is_source(p))


def runs_writing_tool(segments):
    """True when a command of the line may write sources legitimately. `segments` holds each command's words."""
    for words in segments:
        prog = words[0]
        name = os.path.basename(prog)
        first = next((w for w in words[1:] if not w.startswith("-")), "")
        if name in WRITING_TOOLS or prog.startswith(REPO_SCRIPT_PREFIXES):
            return True
        if name == "git" and git_writes(words[1:]):
            return True
        if name == "gh" and "checkout" in words:
            return True
        # The whole name: `shellcheck` and `shasum` start with `sh` but run nothing.
        if re.sub(r"^(python)3?[\d.]*$", r"\g<1>3", name) in INTERPRETERS and first.startswith(REPO_SCRIPT_PREFIXES):
            return True
    return False


def git_writes(args):
    i = 0
    while i < len(args) and args[i].startswith("-"):
        i += 2 if args[i] in ("-C", "-c", "--git-dir", "--work-tree") else 1
    return i < len(args) and args[i] in GIT_WRITING


def store_path(data):
    key = "{}-{}".format(data.get("session_id", "s"), data.get("tool_use_id", "t"))
    safe = "".join(c if c.isalnum() or c in "-_" else "_" for c in key)
    return os.path.join(store_dir(), safe + ".json")


def store_dir():
    return os.path.join(tempfile.gettempdir(), "kinige-hooks")


def save(data, workdir):
    if data.get("tool_name") == "Monitor":
        return  # PostToolUse does not run for Monitor, so a snapshot would never be compared
    root = kinige_root(workdir) or kinige_root(str(data.get("cwd") or ""))
    if root is None:
        return
    files = dirty_files(root)
    if files is None:
        return
    os.makedirs(store_dir(), exist_ok=True)
    drop_stale()
    with open(store_path(data), "w", encoding="utf-8") as f:
        json.dump({"root": root, "head": head(root), "files": files}, f)


def head(root):
    out = subprocess.run(["git", "-C", root, "rev-parse", "-q", "--verify", "HEAD"], capture_output=True, text=True,
                         timeout=10)
    return out.stdout.strip() if out.returncode == 0 else ""


def committed_files(root, old, new):
    """{path: content hash} of the files the commits between `old` and `new` touched (a script edit committed in the
    same command, `python3 fix.py && git commit -am x`, is clean again afterwards)."""
    if not old or not new or old == new:
        return {}
    out = subprocess.run(["git", "-C", root, "diff", "--name-only", "-z", old, new], capture_output=True, timeout=30)
    if out.returncode != 0:
        return {}
    paths = [p for p in out.stdout.decode("utf-8", "surrogateescape").split("\0") if p]
    return {p: file_hash(os.path.join(root, p)) for p in paths}


def drop_stale():
    """Snapshots whose post never ran (a Monitor command, a call denied at a prompt) are removed after a day."""
    now = time.time()
    try:
        names = os.listdir(store_dir())
    except OSError:
        return
    for name in names:
        path = os.path.join(store_dir(), name)
        try:
            if now - os.path.getmtime(path) > STALE_SECONDS:
                os.remove(path)
        except OSError:
            pass


def compare(data, segments):
    """The list of source files the command rewrote by script, or [] (also when there is no snapshot)."""
    path = store_path(data)
    try:
        with open(path, encoding="utf-8") as f:
            snap = json.load(f)
    except (OSError, ValueError):
        return []
    finally:
        try:
            os.remove(path)
        except OSError:
            pass
    if runs_writing_tool(segments):
        return []
    after = dirty_files(snap["root"])
    if after is None:
        return []
    committed = committed_files(snap["root"], snap.get("head", ""), head(snap["root"]))
    after = dict(committed, **after)
    return changed_sources(snap["files"], after)
